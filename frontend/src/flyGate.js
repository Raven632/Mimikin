// Окно игры вырастает из карточки за 240 мс (windowFly.js), и любая перерисовка окна за это время — кадр, который
// не успел: ответ сервера (сейвы, моменты, прохождения, перевод) ставит состояние, и всё окно в несколько сотен
// узлов пересчитывается посреди полёта. Ворота держат такие обновления, пока окно не село, и применяют их разом
// сразу после посадки. Окно без полёта (ссылка ?game=, поиск, «меньше анимаций») открыто с самого начала: ничего
// не откладывается и не ждёт
export function createGate(open) {
  let isOpen = !!open;
  let queue = [];
  return {
    get open() { return isOpen; },
    // Закрыты — запоминаем, открыты — выполняем сразу. Порядок сохраняется: последнее обновление остаётся последним
    run(fn) { if (isOpen) fn(); else queue.push(fn); },
    // Окно село: всё отложенное — одной пачкой, React сведёт её в одну перерисовку
    release() {
      if (isOpen) return;
      isOpen = true;
      const todo = queue;
      queue = [];
      todo.forEach((fn) => fn());
    },
  };
}
